"""Small structural contracts. No concrete optimizer or benchmark imports."""
from pathlib import Path
from typing import Any, Protocol, runtime_checkable
from .domain import (CandidateBatch, EvaluationBatch,
                     OptimizerSpec, RunCheckpoint, RunOutcome, TaskDescription, TaskSpec)


# Re-export the mathematical API for existing import sites.
from .optimizer import Optimizer, Checkpointable, YValues
import pandas as pd


class OptimizerClient(Protocol):
    async def suggest(self, n: int = 1) -> pd.DataFrame: ...
    async def observe(self, X: pd.DataFrame, y: YValues) -> None: ...
    async def close(self) -> None: ...


class Benchmark(Protocol):
    async def describe(self) -> TaskDescription: ...
    async def evaluate(self, batch: CandidateBatch) -> EvaluationBatch: ...
    async def close(self) -> None: ...


@runtime_checkable
class PhysicalObservationClient(Protocol):
    """Optional runtime context; it does not extend the mathematical Optimizer API."""
    async def observe_evaluated(self, X: pd.DataFrame, y: YValues, physical_X) -> None: ...


@runtime_checkable
class NativeOptimizerClient(Protocol):
    async def save_state(self) -> Any: ...
    async def load_state(self, state: Any) -> None: ...


@runtime_checkable
class NativeBenchmarkClient(Protocol):
    async def save_state(self) -> Any: ...
    async def load_state(self, state: Any) -> None: ...


class Runtime(Protocol):
    """Return clients; heavy implementations will run in their own Python."""
    async def open_optimizer(self, spec: OptimizerSpec, environment: Path,
                             task: TaskDescription, seed: int) -> OptimizerClient: ...
    async def open_benchmark(self, spec: TaskSpec, environment: Path, seed: int) -> Benchmark: ...


class RunStore(Protocol):
    """The single controller is the only caller/writer."""
    def checkpoint(self, run_id: str) -> RunCheckpoint | None: ...
    def save_checkpoint(self, checkpoint: RunCheckpoint) -> None: ...
    def committed_checkpoint(self, run_id: str) -> RunCheckpoint | None: ...
    def outcome(self, run_id: str) -> RunOutcome | None: ...
    def save_outcome(self, outcome: RunOutcome) -> None: ...
